/** ProductoResponse (real) + activo, idMarca, idCategoria y especificaciones (propuesta → César). */
export function aProductoResponse(p) {
  return {
    id: p.id,
    nombre: p.nombre,
    descripcion: p.descripcion,
    precio: p.precio,
    imagenUrl: p.imagenUrl,
    marca: marcas.find((m) => m.id === p.idMarca)?.nombre ?? '',
    categoria: categorias.find((c) => c.id === p.idCategoria)?.nombre ?? '',
    activo: p.activo,
    idMarca: p.idMarca,
    idCategoria: p.idCategoria,
    especificaciones: p.especificaciones ?? [],
  };
}
